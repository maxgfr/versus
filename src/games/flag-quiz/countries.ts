export interface Country {
  code: string
  name: string
  /** The flag emoji, built from the two regional-indicator letters of `code`. */
  flag: string
  /** Indices in `COUNTRIES` of the wrong answers, most tempting first. */
  traps: number[]
}

const flagOf = (code: string) =>
  String.fromCodePoint(...[...code].map((l) => 0x1f1e6 + l.charCodeAt(0) - 65))

const position = new Map(ROWS.map(([code], i) => [code, i]))

export const COUNTRIES: Country[] = ROWS.map(([code, name, traps]) => ({
  code,
  name,
  flag: flagOf(code),
  traps: traps.split(' ').map((t) => position.get(t) ?? -1),
}))
